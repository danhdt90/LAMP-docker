#!/bin/bash

# Script to manage local domain configuration
# Usage: ./manage-domains.sh [command]

DOMAINS_FILE=".domains.map"
NGINX_DOMAINS_FILE="src/.nginx-domains.conf"

host_shell() {
    local command_string="$1"
    local repo_dir="$PWD"

    if command -v flatpak-spawn >/dev/null 2>&1; then
        flatpak-spawn --host sh -lc "cd \"$repo_dir\" && $command_string"
    else
        sh -lc "cd \"$repo_dir\" && $command_string"
    fi
}

root_shell() {
    local command_string="$1"
    local repo_dir="$PWD"
    local quoted_command
    quoted_command=$(printf '%q' "$command_string")

    if command -v flatpak-spawn >/dev/null 2>&1; then
        flatpak-spawn --host sh -lc "cd \"$repo_dir\" && pkexec sh -lc $quoted_command"
    else
        pkexec sh -lc "$command_string"
    fi
}

# Function to get all folders in src directory
get_src_folders() {
    if [ -d "src" ]; then
        find src -maxdepth 1 -type d -not -path "src" -exec basename {} \;
    fi
}

# Function to generate domains array dynamically
generate_domains() {
    local domains=()
    while IFS= read -r folder; do
        if [ -n "$folder" ]; then
            domains+=("$folder.test")
        fi
    done < <(get_src_folders)
    echo "${domains[@]}"
}

show_help() {
    echo "Usage: $0 [command]"
    echo ""
    echo "Commands:"
    echo "  setup               - Setup one domain (interactive)"
    echo "  remove              - Remove one domain (interactive)"
    echo "  list                - List configured domain mappings"
    echo "  status              - Show current hosts configuration"
    echo "  restart-nginx       - Restart nginx container"
    echo "  scan                - Scan src folder for projects"
    echo ""
    echo "Current domain mappings:"
    list_domains
    echo ""
    echo "Note: This script may require sudo privileges to modify /etc/hosts"
}

ensure_domains_file() {
    if [ ! -f "$DOMAINS_FILE" ]; then
        touch "$DOMAINS_FILE"
    fi
}

normalize_domain() {
    local input="$1"
    input="${input#http://}"
    input="${input#https://}"
    input="${input%%/*}"

    echo "$input"
}

validate_source_path() {
    local source_path="$1"

    # Accept either "foo/bar" or "src/foo/bar"; normalize to path under src/
    if [[ "$source_path" == src/* ]]; then
        source_path="${source_path#src/}"
    fi

    if [[ -z "$source_path" ]]; then
        return 1
    fi

    if [[ "$source_path" == *".."* ]]; then
        return 1
    fi

    if [ ! -d "src/$source_path" ]; then
        return 1
    fi

    echo "$source_path"
}

generate_nginx_domains_config() {
    ensure_domains_file

    {
        echo "# Auto-generated by manage-domains.sh"
        echo "# Do not edit manually"
        echo ""
    } > "$NGINX_DOMAINS_FILE"

    while IFS='|' read -r domain path; do
        [ -z "$domain" ] && continue
        [ -z "$path" ] && continue

        cat >> "$NGINX_DOMAINS_FILE" << EOF
server {
    listen       80;
    server_name  ${domain};
    root         /usr/share/nginx/html/${path};
    index        index.php index.html index.htm;

    access_log   /tmp/${domain}_access.log main;
    error_log    /tmp/${domain}_error.log;

    if (!-d /usr/share/nginx/html/${path}) {
        return 404;
    }

    location / {
        try_files \$uri \$uri/ /index.php?\$args;
    }

    location ~ \.php\$ {
        fastcgi_pass php:9000;
        fastcgi_param SCRIPT_FILENAME \$document_root\$fastcgi_script_name;
        include fastcgi_params;
    }

    error_page  404              /404.html;
    error_page  500 502 503 504  /50x.html;
    location = /50x.html {
        root   /usr/share/nginx/html;
    }
}

EOF
    done < "$DOMAINS_FILE"
}

add_or_update_mapping() {
    local domain="$1"
    local source_path="$2"

    ensure_domains_file

    if grep -q "^${domain}|" "$DOMAINS_FILE"; then
        awk -F'|' -v d="$domain" -v p="$source_path" 'BEGIN{OFS="|"} $1==d {$2=p} {print}' "$DOMAINS_FILE" > "${DOMAINS_FILE}.tmp" && mv "${DOMAINS_FILE}.tmp" "$DOMAINS_FILE"
        echo "Updated mapping: $domain -> src/$source_path"
    else
        echo "${domain}|${source_path}" >> "$DOMAINS_FILE"
        echo "Added mapping: $domain -> src/$source_path"
    fi
}

remove_mapping() {
    local domain="$1"

    ensure_domains_file
    sed -i "/^${domain}|/d" "$DOMAINS_FILE"
}

select_domain_from_mappings() {
    ensure_domains_file

    local domains=()
    local paths=()

    while IFS='|' read -r domain path; do
        [ -z "$domain" ] && continue
        [ -z "$path" ] && continue
        domains+=("$domain")
        paths+=("$path")
    done < "$DOMAINS_FILE"

    if [ ${#domains[@]} -eq 0 ]; then
        echo ""
        return 1
    fi

    echo "Danh sach domain da cau hinh:" >&2
    local i
    for i in "${!domains[@]}"; do
        echo "  $((i + 1)). ${domains[$i]} -> src/${paths[$i]}" >&2
    done
    echo "" >&2
    echo "Nhap so thu tu domain can xoa:" >&2
    read -r choice

    if ! [[ "$choice" =~ ^[0-9]+$ ]]; then
        echo ""
        return 1
    fi

    if [ "$choice" -lt 1 ] || [ "$choice" -gt "${#domains[@]}" ]; then
        echo ""
        return 1
    fi

    echo "${domains[$((choice - 1))]}"
}

setup_domains() {
    echo "=== Setting up local domain ==="

    if [ ! -d "src" ]; then
        echo "❌ src/ folder not found!"
        return 1
    fi

    echo "Step 1/2 - Nhap domain (vi du: app.local hoac dev.example.com)"
    read -r input_domain
    local domain
    domain="$(normalize_domain "$input_domain")"

    if [ -z "$domain" ]; then
        echo "❌ Domain khong hop le"
        return 1
    fi

    if [ -z "$domain" ]; then
        echo "❌ Domain khong duoc rong"
        return 1
    fi

    echo "Step 2/2 - Nhap path toi source code trong src/ (vi du: php08 hoac propolife-webs/sources/logasset)"
    read -r input_path
    local source_path
    source_path="$(validate_source_path "$input_path")"

    if [ -z "$source_path" ]; then
        echo "❌ Path khong hop le hoac khong ton tai trong src/"
        return 1
    fi

    echo "🔐 Ban se duoc hoi mat khau root de cap nhat /etc/hosts"
    
    # Add domain to hosts file
    if ! host_shell "grep -q '$domain' /etc/hosts"; then
        echo "Adding $domain to /etc/hosts..."
        root_shell "echo '127.0.0.1    $domain' | tee -a /etc/hosts > /dev/null"
    else
        echo "$domain already exists in /etc/hosts"
    fi

    # Update domain mapping and regenerate nginx domains config
    add_or_update_mapping "$domain" "$source_path"
    generate_nginx_domains_config

    # Restart nginx so the new mapping is loaded
    restart_nginx
    
    echo ""
    echo "✅ Domain setup completed!"
    echo "You can now access: http://$domain"
    echo "Mapped to: src/$source_path"
}

remove_domains() {
    echo "=== Removing local domain ==="

    ensure_domains_file
    local domain
    domain="$(select_domain_from_mappings)"

    if [ -z "$domain" ]; then
        echo "❌ Khong co domain nao de xoa hoac lua chon khong hop le"
        return 1
    fi

    echo "Domain duoc chon: $domain"
    echo "🔐 Ban se duoc hoi mat khau root de cap nhat /etc/hosts"

    if host_shell "grep -q '$domain' /etc/hosts"; then
        echo "Removing $domain from /etc/hosts..."
        root_shell "sed -i '/$domain/d' /etc/hosts"
    else
        echo "$domain not found in /etc/hosts"
    fi

    remove_mapping "$domain"
    generate_nginx_domains_config
    restart_nginx

    echo "✅ Domain removed successfully!"
}

list_domains() {
    ensure_domains_file
    if [ ! -s "$DOMAINS_FILE" ]; then
        echo "  (empty)"
        return
    fi

    while IFS='|' read -r domain path; do
        [ -z "$domain" ] && continue
        [ -z "$path" ] && continue
        echo "  - http://$domain -> src/$path"
    done < "$DOMAINS_FILE"
}

scan_folders() {
    echo "=== Scanning src/ folder for projects ==="
    echo ""
    
    if [ ! -d "src" ]; then
        echo "❌ src/ folder not found!"
        return 1
    fi
    
    local folders=($(get_src_folders))
    
    if [ ${#folders[@]} -eq 0 ]; then
        echo "No folders found in src/ directory."
        return 1
    fi
    
    echo "Found ${#folders[@]} project(s):"
    for folder in "${folders[@]}"; do
        local domain="$folder.test"
        local path="src/$folder"
        
        echo "📁 $folder"
        echo "   Domain: http://$domain"
        echo "   Path: $path"
        
        # Check if it has common web files
        if [ -f "$path/index.php" ] || [ -f "$path/index.html" ] || [ -f "$path/package.json" ]; then
            echo "   Status: ✅ Web project detected"
        else
            echo "   Status: ⚠️  No web files detected"
        fi
        echo ""
    done
}

show_status() {
    echo "=== Current hosts configuration ==="
    echo "Checking /etc/hosts for configured domains:"
    echo ""

    ensure_domains_file
    local domains=()
    while IFS='|' read -r domain _; do
        [ -n "$domain" ] && domains+=("$domain")
    done < "$DOMAINS_FILE"

    if [ ${#domains[@]} -eq 0 ]; then
        echo "(No configured domains in $DOMAINS_FILE)"
    fi

    for domain in "${domains[@]}"; do
        if host_shell "grep -q '$domain' /etc/hosts"; then
            echo "✅ $domain - configured"
        else
            echo "❌ $domain - not configured"
        fi
    done
    
    echo ""
    echo "=== Docker services status ==="
    host_shell 'docker compose ps'
}

restart_nginx() {
    echo "=== Restarting nginx container ==="
    host_shell 'docker compose restart nginx'
    echo "✅ Nginx restarted!"
}

case "$1" in
    "setup")
        setup_domains
        ;;
    "remove")
        remove_domains
        ;;
    "list")
        list_domains
        ;;
    "status")
        show_status
        ;;
    "restart-nginx")
        restart_nginx
        ;;
    "scan")
        scan_folders
        ;;
    *)
        show_help
        ;;
esac
